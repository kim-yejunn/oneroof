-- P8: AI interpretation of agency replies. Advisory text for the reviewer; nothing reads it to decide.
CREATE TABLE reply_interpretation
(
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clarification_id BIGINT NOT NULL UNIQUE REFERENCES clarification_request (id),
  interpreter      TEXT   NOT NULL,
  fell_back        BOOLEAN NOT NULL,
  summary          TEXT   NOT NULL,
  stance           TEXT   NOT NULL,
  reasons          TEXT   NOT NULL,
  evidence         TEXT   NOT NULL,
  amounts          TEXT   NOT NULL,
  gaps             TEXT   NOT NULL,
  follow_ups       TEXT   NOT NULL,
  notes            TEXT   NOT NULL,
  provenance       TEXT   NOT NULL,
  recorded_on      DATE   NOT NULL,
  correlation_id   TEXT   NOT NULL
);

DROP VIEW clarification_overview;
CREATE VIEW clarification_overview AS
SELECT q.id,
       q.kind,
       q.subject_type,
       q.subject_id,
       q.agency_ids,
       q.title,
       q.question,
       q.status,
       q.sent_on,
       q.due_on,
       q.notice_reference,
       q.outcome,
       q.reply_text,
       q.reply_account,
       q.replied_on,
       q.correlation_id,
       i.interpreter AS ai_interpreter,
       i.fell_back   AS ai_fell_back,
       i.summary     AS ai_summary,
       i.stance      AS ai_stance,
       i.reasons     AS ai_reasons,
       i.evidence    AS ai_evidence,
       i.amounts     AS ai_amounts,
       i.gaps        AS ai_gaps,
       i.follow_ups  AS ai_follow_ups,
       i.notes       AS ai_notes
FROM clarification_request q
       LEFT JOIN reply_interpretation i ON i.clarification_id = q.id;
