-- Change and exception flows: master corrections, clarification requests to agencies, payment holds,
-- retrospective findings and referrals to audit.

-- A reported correction to the agency master. The identity rows carry the values; this keeps who
-- reported the change, why, and what it replaced.
CREATE TABLE master_change
(
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id       TEXT NOT NULL UNIQUE,
  agency_id      TEXT NOT NULL,
  kind           TEXT NOT NULL,
  previous_value TEXT NOT NULL,
  new_value      TEXT NOT NULL,
  effective_from DATE NOT NULL,
  reason         TEXT NOT NULL,
  reported_by    TEXT NOT NULL,
  provenance     TEXT NOT NULL,
  recorded_on    DATE NOT NULL
);

-- A review can be replaced when its limit unit changes, and resubmitted after a clarification.
-- Only one live review may exist per unit and month.
ALTER TABLE rebate_review DROP CONSTRAINT rebate_review_period_ym_unit_key_key;
CREATE UNIQUE INDEX rebate_review_live_unit_idx ON rebate_review (period_ym, unit_key) WHERE status <> 'SUPERSEDED';
ALTER TABLE rebate_review ADD COLUMN round INT NOT NULL DEFAULT 1;
ALTER TABLE rebate_review ADD COLUMN superseded_by_change BIGINT;

-- Months already settled under the sales support team's authority that a correction shows needed
-- the executive. Payments are not reversed; the executive confirms after the fact or refers to audit.
CREATE TABLE retrospective_finding
(
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_ym         TEXT    NOT NULL,
  unit_key          TEXT    NOT NULL,
  member_agency_ids TEXT    NOT NULL,
  rebate_ids        TEXT    NOT NULL,
  total_krw         BIGINT  NOT NULL,
  limit_krw         BIGINT  NOT NULL,
  approved_by       TEXT    NOT NULL,
  required_approver TEXT    NOT NULL,
  status            TEXT    NOT NULL,
  master_change_id  BIGINT  NOT NULL,
  title             TEXT    NOT NULL,
  rationale         TEXT    NOT NULL,
  correlation_id    TEXT    NOT NULL,
  version           BIGINT  NOT NULL,
  UNIQUE (period_ym, unit_key)
);

-- Payee account and hold reason for each payment instruction.
ALTER TABLE payment_instruction ADD COLUMN payee_account TEXT;
ALTER TABLE payment_instruction ADD COLUMN hold_reason TEXT;

-- A question sent to agencies, and their answer.
CREATE TABLE clarification_request
(
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind             TEXT   NOT NULL,
  subject_type     TEXT   NOT NULL,
  subject_id       TEXT   NOT NULL,
  agency_ids       TEXT   NOT NULL,
  title            TEXT   NOT NULL,
  question         TEXT   NOT NULL,
  status           TEXT   NOT NULL,
  sent_on          DATE   NOT NULL,
  due_on           DATE   NOT NULL,
  notice_reference TEXT,
  outcome          TEXT,
  reply_text       TEXT,
  reply_account    TEXT,
  replied_on       DATE,
  correlation_id   TEXT   NOT NULL,
  version          BIGINT NOT NULL
);
CREATE INDEX clarification_by_subject_idx ON clarification_request (subject_type, subject_id);

-- Matters handed to audit. A referral closes this review round, not the obligation to follow up.
CREATE TABLE audit_referral
(
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_type   TEXT NOT NULL,
  subject_id     TEXT NOT NULL,
  title          TEXT NOT NULL,
  reason         TEXT NOT NULL,
  referred_by    TEXT NOT NULL,
  referred_on    DATE NOT NULL,
  status         TEXT NOT NULL,
  correlation_id TEXT NOT NULL
);

-- Read models. A review may now have several approval requests (resubmission after a
-- clarification); the overview shows the latest one.
DROP VIEW review_overview;
CREATE VIEW review_overview AS
SELECT r.id,
       r.period_ym                                    AS period,
       r.unit_key,
       r.related_group,
       r.member_agency_ids,
       r.total_krw,
       r.limit_krw,
       r.exceeds_limit,
       r.required_approver,
       r.status,
       r.title,
       r.rationale,
       r.correlation_id,
       a.id                                           AS approval_request_id,
       a.status                                       AS approval_status,
       a.decided_by_role,
       a.decided_by_name,
       a.decided_on,
       a.decision_comment,
       (SELECT count(*) FROM rebate_claim c WHERE c.review_id = r.id) AS claim_count,
       (SELECT count(*) FROM rebate_claim c WHERE c.review_id = r.id AND c.settlement_status = 'PAID') AS paid_count,
       r.round,
       q.id                                           AS clarification_id,
       q.status                                       AS clarification_status
FROM rebate_review r
       LEFT JOIN LATERAL (SELECT * FROM approval_request x
                          WHERE x.subject_type = 'RebateReview' AND x.subject_id = r.id::text
                          ORDER BY x.id DESC LIMIT 1) a ON true
       LEFT JOIN LATERAL (SELECT * FROM clarification_request y
                          WHERE y.subject_type = 'RebateReview' AND y.subject_id = r.id::text
                          ORDER BY y.id DESC LIMIT 1) q ON true;

DROP VIEW payment_overview;
CREATE VIEW payment_overview AS
SELECT p.id,
       p.reference_type,
       p.reference_id,
       p.agency_id,
       g.name AS agency_name,
       p.amount_krw,
       p.status,
       p.gateway_reference,
       p.bank_reference,
       p.requested_on,
       p.correlation_id,
       c.period_ym AS period,
       c.review_id,
       p.payee_account,
       p.hold_reason,
       q.id     AS clarification_id,
       q.status AS clarification_status
FROM payment_instruction p
       JOIN agency g ON g.agency_id = p.agency_id
       LEFT JOIN rebate_claim c ON p.reference_type = 'RebateClaim' AND c.rebate_id = p.reference_id
       LEFT JOIN LATERAL (SELECT * FROM clarification_request y
                          WHERE y.subject_type = 'PaymentInstruction' AND y.subject_id = p.id::text
                          ORDER BY y.id DESC LIMIT 1) q ON true;

CREATE VIEW clarification_overview AS
SELECT q.id,
       q.kind,
       q.subject_type,
       q.subject_id,
       q.agency_ids,
       q.title,
       q.question,
       q.status,
       q.sent_on,
       q.due_on,
       q.notice_reference,
       q.outcome,
       q.reply_text,
       q.reply_account,
       q.replied_on,
       q.correlation_id
FROM clarification_request q;

CREATE VIEW finding_overview AS
SELECT f.id,
       f.period_ym AS period,
       f.unit_key,
       f.member_agency_ids,
       f.rebate_ids,
       f.total_krw,
       f.limit_krw,
       f.approved_by,
       f.required_approver,
       f.status,
       f.master_change_id,
       f.title,
       f.rationale,
       f.correlation_id,
       a.id     AS approval_request_id,
       a.status AS approval_status,
       a.decision_comment
FROM retrospective_finding f
       LEFT JOIN LATERAL (SELECT * FROM approval_request x
                          WHERE x.subject_type = 'RetrospectiveFinding' AND x.subject_id = f.id::text
                          ORDER BY x.id DESC LIMIT 1) a ON true;
