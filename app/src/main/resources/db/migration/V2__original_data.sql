-- Tables holding records loaded from the original data room. source_ref points back to the
-- file and line each record came from. Modules do not share foreign keys.

CREATE TABLE agency
(
  agency_id       TEXT PRIMARY KEY,
  name            TEXT    NOT NULL,
  business_reg_no TEXT    NOT NULL,
  rebate_eligible BOOLEAN NOT NULL,
  registered_date DATE    NOT NULL,
  source_ref      TEXT    NOT NULL
);

CREATE TABLE agency_identity
(
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agency_id      TEXT NOT NULL,
  kind           TEXT NOT NULL,
  identity_value TEXT NOT NULL,
  effective_from DATE NOT NULL,
  effective_to   DATE,
  provenance     TEXT NOT NULL,
  source_ref     TEXT NOT NULL
);
CREATE INDEX agency_identity_by_agency_idx ON agency_identity (agency_id, kind, effective_from);
CREATE INDEX agency_identity_by_value_idx ON agency_identity (kind, identity_value);

CREATE TABLE rebate_claim
(
  rebate_id             TEXT PRIMARY KEY,
  agency_id             TEXT   NOT NULL,
  period_ym             TEXT   NOT NULL,
  sales_performance_krw BIGINT NOT NULL,
  amount_krw            BIGINT NOT NULL,
  original_status       TEXT   NOT NULL,
  original_approver     TEXT,
  original_payment_date DATE,
  source_ref            TEXT   NOT NULL
);
CREATE INDEX rebate_claim_by_period_idx ON rebate_claim (period_ym, agency_id);

CREATE TABLE receivable
(
  ar_id           TEXT PRIMARY KEY,
  agency_id       TEXT,
  customer_id     TEXT,
  invoice_date    DATE   NOT NULL,
  due_date        DATE   NOT NULL,
  amount_krw      BIGINT NOT NULL,
  outstanding_krw BIGINT NOT NULL,
  aging_days      INT    NOT NULL,
  source_ref      TEXT   NOT NULL
);
CREATE INDEX receivable_by_agency_idx ON receivable (agency_id);

CREATE TABLE deposit
(
  deposit_id      TEXT PRIMARY KEY,
  agency_id       TEXT   NOT NULL,
  deposit_date    DATE   NOT NULL,
  amount_krw      BIGINT NOT NULL,
  bank_account_no TEXT   NOT NULL,
  matched_ar_id   TEXT,
  source_ref      TEXT   NOT NULL
);
CREATE INDEX deposit_by_agency_idx ON deposit (agency_id);
