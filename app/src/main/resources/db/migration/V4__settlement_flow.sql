-- Incoming business events. The primary key makes each event take effect at most once.
CREATE TABLE inbox_event
(
  event_id      TEXT PRIMARY KEY,
  event_type    TEXT NOT NULL,
  summary       TEXT NOT NULL,
  received_at   TIMESTAMP WITH TIME ZONE NOT NULL,
  business_date DATE NOT NULL
);

-- System-owned settlement state next to the unchanged source columns.
ALTER TABLE rebate_claim ADD COLUMN settlement_status TEXT;
UPDATE rebate_claim
SET settlement_status = CASE original_status
                          WHEN '승인' THEN 'SETTLED_IN_SOURCE'
                          WHEN '반려' THEN 'REJECTED_IN_SOURCE'
                          ELSE 'PENDING' END;
ALTER TABLE rebate_claim ALTER COLUMN settlement_status SET NOT NULL;
ALTER TABLE rebate_claim ADD COLUMN review_id BIGINT;
CREATE INDEX rebate_claim_by_review_idx ON rebate_claim (review_id);

CREATE TABLE settlement_batch
(
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_ym       TEXT NOT NULL UNIQUE,
  source_event_id TEXT NOT NULL,
  opened_on       DATE NOT NULL
);

-- One review per limit unit (a related group or a single agency) per month.
CREATE TABLE rebate_review
(
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id          BIGINT  NOT NULL,
  unit_key          TEXT    NOT NULL,
  period_ym         TEXT    NOT NULL,
  related_group     BOOLEAN NOT NULL,
  member_agency_ids TEXT    NOT NULL,
  total_krw         BIGINT  NOT NULL,
  limit_krw         BIGINT  NOT NULL,
  exceeds_limit     BOOLEAN NOT NULL,
  required_approver TEXT    NOT NULL,
  status            TEXT    NOT NULL,
  title             TEXT    NOT NULL,
  rationale         TEXT    NOT NULL,
  correlation_id    TEXT    NOT NULL,
  version           BIGINT  NOT NULL,
  UNIQUE (period_ym, unit_key)
);

CREATE TABLE approval_request
(
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_type     TEXT   NOT NULL,
  subject_id       TEXT   NOT NULL,
  required_role    TEXT   NOT NULL,
  title            TEXT   NOT NULL,
  rationale        TEXT   NOT NULL,
  amount_krw       BIGINT NOT NULL,
  status           TEXT   NOT NULL,
  requested_on     DATE   NOT NULL,
  decided_by_role  TEXT,
  decided_by_name  TEXT,
  decided_on       DATE,
  decision_comment TEXT,
  correlation_id   TEXT   NOT NULL,
  version          BIGINT NOT NULL
);
CREATE INDEX approval_request_by_role_idx ON approval_request (required_role, status);
CREATE INDEX approval_request_by_subject_idx ON approval_request (subject_type, subject_id);

CREATE TABLE payment_instruction
(
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_type    TEXT   NOT NULL,
  reference_id      TEXT   NOT NULL,
  agency_id         TEXT   NOT NULL,
  amount_krw        BIGINT NOT NULL,
  status            TEXT   NOT NULL,
  gateway_reference TEXT,
  bank_reference    TEXT,
  requested_on      DATE   NOT NULL,
  correlation_id    TEXT   NOT NULL,
  version           BIGINT NOT NULL,
  UNIQUE (reference_type, reference_id)
);
