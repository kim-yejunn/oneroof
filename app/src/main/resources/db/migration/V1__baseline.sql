-- Spring Modulith event publication registry (schema v2). Events are stored in the same
-- transaction as the state change that raised them and delivered after commit, which makes this
-- table the transactional outbox for events between modules.
CREATE TABLE event_publication
(
  id                     UUID NOT NULL,
  listener_id            TEXT NOT NULL,
  event_type             TEXT NOT NULL,
  serialized_event       TEXT NOT NULL,
  publication_date       TIMESTAMP WITH TIME ZONE NOT NULL,
  completion_date        TIMESTAMP WITH TIME ZONE,
  status                 TEXT,
  completion_attempts    INT,
  last_resubmission_date TIMESTAMP WITH TIME ZONE,
  PRIMARY KEY (id)
);
CREATE INDEX event_publication_serialized_event_hash_idx ON event_publication USING hash (serialized_event);
CREATE INDEX event_publication_by_completion_date_idx ON event_publication (completion_date);

-- Append-only audit trail.
CREATE TABLE audit_log
(
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recorded_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  business_date  DATE NOT NULL,
  actor_role     TEXT NOT NULL,
  action         TEXT NOT NULL,
  subject_type   TEXT NOT NULL,
  subject_id     TEXT NOT NULL,
  detail         TEXT NOT NULL,
  provenance     TEXT NOT NULL,
  correlation_id TEXT
);
CREATE INDEX audit_log_by_subject_idx ON audit_log (subject_type, subject_id, id);
CREATE INDEX audit_log_by_correlation_idx ON audit_log (correlation_id);
