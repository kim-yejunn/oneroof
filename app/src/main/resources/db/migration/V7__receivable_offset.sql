-- P7: rebates offset against long-overdue receivables, decided by finance.

-- The rebate owed stays in amount_krw; offset_krw of it is set off against the agency's overdue
-- receivables and only the rest is sent to the bank.
ALTER TABLE payment_instruction
  ADD COLUMN offset_krw      BIGINT NOT NULL DEFAULT 0,
  ADD COLUMN offset_basis    TEXT,
  ADD COLUMN offset_round    INT    NOT NULL DEFAULT 0,
  ADD COLUMN offset_decision TEXT;

-- Changes to what an agency owes that happened after the aging report: offsets this system made and
-- deposits reported during the demonstration. The original receivable rows are never changed.
CREATE TABLE receivable_adjustment
(
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ar_id          TEXT   NOT NULL REFERENCES receivable (ar_id),
  agency_id      TEXT   NOT NULL,
  kind           TEXT   NOT NULL,
  amount_krw     BIGINT NOT NULL,
  reference      TEXT   NOT NULL,
  provenance     TEXT   NOT NULL,
  recorded_on    DATE   NOT NULL,
  correlation_id TEXT   NOT NULL,
  UNIQUE (kind, reference, ar_id)
);
CREATE INDEX receivable_adjustment_agency_idx ON receivable_adjustment (agency_id);

DROP VIEW payment_overview;
CREATE VIEW payment_overview AS
SELECT p.id,
       p.reference_type,
       p.reference_id,
       p.agency_id,
       g.name                     AS agency_name,
       p.amount_krw,
       p.status,
       p.gateway_reference,
       p.bank_reference,
       p.requested_on,
       p.correlation_id,
       c.period_ym                AS period,
       c.review_id,
       p.payee_account,
       p.hold_reason,
       q.id                       AS clarification_id,
       q.status                   AS clarification_status,
       p.offset_krw,
       p.amount_krw - p.offset_krw AS net_krw,
       p.offset_basis,
       p.offset_round,
       p.offset_decision
FROM payment_instruction p
       JOIN agency g ON g.agency_id = p.agency_id
       LEFT JOIN rebate_claim c ON p.reference_type = 'RebateClaim' AND c.rebate_id = p.reference_id
       LEFT JOIN LATERAL (SELECT * FROM clarification_request y
                          WHERE y.subject_type = 'PaymentInstruction' AND y.subject_id = p.id::text
                          ORDER BY y.id DESC LIMIT 1) q ON true;

-- Agency receivables with what has happened to them since the aging report.
CREATE VIEW receivable_overview AS
SELECT r.ar_id,
       r.agency_id,
       g.name                                                         AS agency_name,
       r.invoice_date,
       r.due_date,
       r.amount_krw,
       r.outstanding_krw                                              AS original_outstanding_krw,
       coalesce(sum(a.amount_krw) FILTER (WHERE a.kind = 'OFFSET'), 0)   AS offset_krw,
       coalesce(sum(a.amount_krw) FILTER (WHERE a.kind = 'DEPOSIT'), 0)  AS deposit_krw,
       r.outstanding_krw - coalesce(sum(a.amount_krw), 0)             AS outstanding_krw,
       r.aging_days,
       r.source_ref
FROM receivable r
       JOIN agency g ON g.agency_id = r.agency_id
       LEFT JOIN receivable_adjustment a ON a.ar_id = r.ar_id
WHERE r.agency_id IS NOT NULL
GROUP BY r.ar_id, g.name;
