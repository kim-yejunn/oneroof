-- The rebate payment limit as a dated rule rather than a constant, so a policy change becomes a
-- new row and earlier months are still judged by the rule in force at the time.
CREATE TABLE rebate_limit_policy
(
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monthly_limit_krw BIGINT NOT NULL,
  effective_from    DATE   NOT NULL,
  provenance        TEXT   NOT NULL,
  source_ref        TEXT   NOT NULL
);

